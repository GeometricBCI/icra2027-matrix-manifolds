"""Generate the SO(3) vignette from one right-handed 3-D construction.

Run from any directory with Python 3. No external dependencies.

For an axis n, p(theta) = r * (u*cos(theta) + v*sin(theta)),
where u cross v = n. Hence dp/dtheta = n cross p: positive
rotation follows the right-hand rule. Arrows use this tangent,
projected with the same orthographic camera as the cube and axes.

Convention: https://modernrobotics.northwestern.edu/
nu-gm-book-resource/3-2-2-angular-velocities/
"""

from math import ceil, cos, pi, sin, sqrt
from pathlib import Path


def add(a, b):
    return tuple(x + y for x, y in zip(a, b))


def mul(k, a):
    return tuple(k * x for x in a)


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def norm(a):
    return sqrt(dot(a, a))


EX, EY, EZ = (1, 0, 0), (0, 1, 0), (0, 0, 1)
# Camera azimuth 45 degrees, elevation 30 degrees, looking at the origin.
RIGHT = (-1 / sqrt(2), 1 / sqrt(2), 0)
UP = (-1 / (2 * sqrt(2)), -1 / (2 * sqrt(2)), sqrt(3) / 2)
VIEW = cross(RIGHT, UP)  # Toward the camera.
CENTER, SCALE, HALF = (80, 76), 50, 0.4


def project(p):
    return (CENTER[0] + SCALE * dot(RIGHT, p),
            CENTER[1] - SCALE * dot(UP, p))


def project_vector(v):
    return (SCALE * dot(RIGHT, v), -SCALE * dot(UP, v))


def xy(p):
    return f"{p[0]:.3f},{p[1]:.3f}"


def hidden_by_cube(p):
    """Does the ray from p toward the camera hit the opaque cube?"""
    lo, hi = float('-inf'), float('inf')
    for coord, direction in zip(p, VIEW):
        first, last = sorted(((-HALF - coord) / direction,
                              (HALF - coord) / direction))
        lo, hi = max(lo, first), min(hi, last)
    return hi >= max(lo, 1e-8)


def arrow(point, tangent, color, width=1.6, length=6.4):
    tip, v = project(point), project_vector(tangent)
    v = mul(1 / norm(v), v)
    normal = (-v[1], v[0])
    base = add(tip, mul(-length, v))
    left, right = add(base, mul(2.65, normal)), add(base, mul(-2.65, normal))
    # The bisector of the arrowhead must equal the projected positive tangent.
    assert dot(v, project_vector(tangent)) > 0
    return (f'<path d="M{xy(left)} L{xy(tip)} L{xy(right)}" '
            f'stroke="{color}" stroke-width="{width}"/>')


# Validate the physical frame and camera independently of SVG styling.
assert cross(EX, EY) == EZ
for basis in (EX, EY, EZ, RIGHT, UP, VIEW):
    assert abs(norm(basis) - 1) < 1e-12
assert abs(dot(RIGHT, UP)) < 1e-12
assert abs(dot(RIGHT, VIEW)) < 1e-12
assert abs(dot(UP, VIEW)) < 1e-12

parts = ['''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 150" fill="none">
<title>Positive rotations about the y and z axes</title>
<desc>A cube and a right-handed coordinate frame share one orthographic projection. Green and ochre arcs are projections of circles centered at the origin in the xz and xy planes, respectively. Their arrows follow positive rotation about the matching y and z axes. Dashed portions are behind the origin; the cube occludes hidden portions. This illustrates spatial rotations, not the shape of SO(3).</desc>
<metadata>Generated by artwork/generate_spatial_rotation.py. Camera: azimuth 45 degrees, elevation 30 degrees. For both arcs, dp/dtheta = n cross p. Cube half-side 0.4; circle radii 1.03 and 1.04.</metadata>
<defs><filter id="spatial-paper" x="-8%" y="-8%" width="116%" height="116%" color-interpolation-filters="sRGB">
<feTurbulence type="fractalNoise" baseFrequency=".72" numOctaves="3" seed="23" stitchTiles="stitch" result="grain"/>
<feColorMatrix in="grain" type="saturate" values="0"/>
<feComponentTransfer><feFuncA type="linear" slope=".16"/></feComponentTransfer>
<feBlend in="SourceGraphic" mode="multiply"/><feComposite in2="SourceGraphic" operator="in"/>
</filter></defs>
<g stroke-linecap="round" stroke-linejoin="round" filter="url(#spatial-paper)">''']

# The three visible faces of an axis-aligned cube, with shared vertices.
a = HALF
faces = [
    ([(-a, -a, a), (-a, a, a), (a, a, a), (a, -a, a)], '#f1e4bc'),
    ([(a, -a, a), (a, a, a), (a, a, -a), (a, -a, -a)], '#e7c5a4'),
    ([(-a, a, a), (-a, a, -a), (a, a, -a), (a, a, a)], '#d9dcb9'),
]
for vertices, color in faces:
    points = ' '.join(xy(project(p)) for p in vertices)
    parts.append(f'<polygon points="{points}" fill="{color}" stroke="#84765a" stroke-width="1.65"/>')

# Sample short segments and sort them by depth for correct crossings.
# A 0.5-degree step has under 0.001 px chord error at this drawing's scale.
segments, tips = [], []


def add_segments(points, color, width, dashed_back=False):
    distance = 0.0
    for p, q in zip(points, points[1:]):
        midpoint = mul(0.5, add(p, q))
        projected_length = norm(add(project(q), mul(-1, project(p))))
        back = dashed_back and dot(midpoint, VIEW) < 0
        on = not back or distance % 6.5 < 3.4
        if on and not hidden_by_cube(midpoint):
            opacity = .54 if back else .97
            stroke_width = 1.05 if back else width
            markup = (f'<path d="M{xy(project(p))} L{xy(project(q))}" '
                      f'stroke="{color}" stroke-width="{stroke_width}" opacity="{opacity}"/>')
            segments.append((dot(midpoint, VIEW), markup))
        distance += projected_length


axis_colors = ['#ae7157', '#758e6d', '#a7875a']
for n, color, length in zip((EX, EY, EZ), axis_colors, (1.32, 1.32, 1.22)):
    # Ray visibility, rather than a guessed overlap, determines the start.
    samples = [mul(length * i / 180, n) for i in range(181)]
    add_segments(samples, color, 1.5)
    tip = mul(length, n)
    tips.append((dot(tip, VIEW), arrow(tip, n, color, 1.5, 5.8)))

max_plane_error = max_radius_error = max_tangent_error = 0.0
for name, n, u, v, radius, start_deg, end_deg, color in [
    ('z', EZ, EX, EY, 1.04, 135, 480, axis_colors[2]),
    ('y', EY, EZ, EX, 1.03, 141, 488, axis_colors[1]),
]:
    assert cross(u, v) == n
    start, end = start_deg * pi / 180, end_deg * pi / 180
    count = ceil((end_deg - start_deg) / .5)
    points = []
    for i in range(count + 1):
        theta = start + (end - start) * i / count
        p = mul(radius, add(mul(cos(theta), u), mul(sin(theta), v)))
        dp = mul(radius, add(mul(-sin(theta), u), mul(cos(theta), v)))
        plane_error = abs(dot(n, p))
        radius_error = abs(norm(p) - radius)
        tangent_error = norm(add(dp, mul(-1, cross(n, p))))
        assert plane_error < 1e-12
        assert radius_error < 1e-12
        assert tangent_error < 1e-12
        max_plane_error = max(max_plane_error, plane_error)
        max_radius_error = max(max_radius_error, radius_error)
        max_tangent_error = max(max_tangent_error, tangent_error)
        points.append(p)
    add_segments(points, color, 1.7, dashed_back=True)
    assert not hidden_by_cube(points[-1])
    assert dot(points[-1], VIEW) > 0
    tips.append((dot(points[-1], VIEW), arrow(points[-1], dp, color)))

parts += [markup for _, markup in sorted(segments + tips, key=lambda item: item[0])]

# Small axis letters make the color/rotation correspondence explicit.
parts.append('''<g font-family="Georgia, serif" font-size="9" font-style="italic" stroke="none">
<text x="24" y="105" fill="#ae7157">x</text>
<text x="132" y="105" fill="#758e6d">y</text>
<text x="84" y="21" fill="#a7875a">z</text>
</g>
<path d="M25.6 40.2L26.7 43.4L29.9 44.5L26.7 45.6L25.6 48.8L24.5 45.6L21.3 44.5L24.5 43.4Z" fill="#e2c784" stroke="#b4a06d" stroke-width=".8"/>
<path d="M124.3 34.4L126.7 31.1M130.9 40.4L134.6 39.3" stroke="#b7ae91" stroke-width="1.2"/>
</g></svg>''')

target = Path(__file__).resolve().parents[1] / 'docs/assets/spatial-rotation-storybook.svg'
target.write_text('\n'.join(parts) + '\n')
print(f'Generated {target.name}; one orthographic camera, right-handed frame, and ray/cube occlusion.')
print(f'Maximum plane/radius/tangent errors: {max_plane_error:.2e}, {max_radius_error:.2e}, {max_tangent_error:.2e}')
